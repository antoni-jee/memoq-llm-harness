"""Regenerate the static text constants from the operator's RTF sources.

The app must not depend on the ``.rtf`` files at runtime, so their text is
baked into Python modules once, here. Re-run this whenever the RTF sources
change:

    python tools\\build_defaults.py

Writes:
    memoq_harness/defaults.py          DEFAULT_HARD_RULES, DEFAULT_VIBE
    memoq_harness/prompt_templates.py  INIT / MT1 / MT2 / MT3 templates
"""

from __future__ import annotations

import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from memoq_harness import rtf  # noqa: E402

PKG = os.path.join(ROOT, "memoq_harness")

# (constant name, filename fragments used to locate the .rtf)
RULE_SOURCES = [
    ("DEFAULT_HARD_RULES", ("rules",)),
    ("DEFAULT_VIBE", ("vibe",)),
]

PROMPT_SOURCES = [
    ("INIT", ("mt", "0"), "Init", "First contact: role, termbase, rules, vibe."),
    ("MT1", ("mt", "1"), "MT1", "First working batch of a new article."),
    ("MT2", ("mt", "2"), "MT2", "Mid-run batch carrying human corrections."),
    ("MT3", ("mt", "3"), "MT3", "Final batch / wrap-up pass."),
]


def load(fragments) -> tuple[str, str]:
    path = rtf.find_rtf(ROOT, *fragments)
    if not path:
        raise SystemExit("No .rtf in %s matching %s" % (ROOT, fragments))
    return rtf.read_rtf_file(path), os.path.basename(path)


def literal(text: str) -> str:
    """Render text as a Python triple-quoted string literal."""
    body = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if body.endswith('"'):
        body = body[:-1] + '\\"'
    return '"""\\\n%s"""' % body


def write(path: str, content: str) -> None:
    with io.open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(content)
    print("wrote %s (%d bytes)" % (os.path.relpath(path, ROOT), len(content.encode("utf-8"))))


def build_defaults() -> None:
    parts = ['''"""Default editorial rule blocks shown in the left panel.

GENERATED by tools/build_defaults.py from the operator's RTF sources.
Edit the .rtf files and re-run that script rather than editing this file.

These are *content*, not code: the operator edits them in the UI and the
edited version is persisted to ``state.json``. The constants here are only the
value a fresh project starts from, and what the "Restore" buttons reset to.

Two distinct things live in the left panel and must not be confused:

* **Hard rules** - the editorial rulebook, free-form prose, injected into the
  system prompt verbatim.
* **Termbase** - the memoQ glossary CSV, a table of term pairs, filtered per
  batch so only the terms that actually occur are spent on tokens.

NOTE FOR CONTRIBUTORS: this file is deliberately non-ASCII. Never bulk-rewrite
it with Windows PowerShell ``Get-Content``/``Set-Content``, which default to
the system ANSI codepage and will double-encode every Cyrillic character.
"""

from __future__ import annotations
''']
    for name, fragments in RULE_SOURCES:
        text, filename = load(fragments)
        parts.append("\n# Source: %s\n%s = %s\n" % (filename, name, literal(text)))
    write(os.path.join(PKG, "defaults.py"), "\n".join(parts))


def build_prompts() -> None:
    parts = ['''"""Operator-authored prompt templates (the "RTF prompt engine").

GENERATED by tools/build_defaults.py from the operator's ``MT *.rtf`` sources.
Edit the .rtf files and re-run that script rather than editing this file.

The workflow these encode is a conversation, not four unrelated prompts:

    Init -> MT1 -> MT2 (repeated) -> MT3

``Init`` establishes the role, the termbase and the rulebook. ``MT1`` opens a
new article. ``MT2`` is the workhorse: it carries the previous batch's human
corrections back to the model. ``MT3`` closes the run. The harness picks one
per batch (see :func:`memoq_harness.prompts.stage_for_batch`) and the operator
can override the choice and rewrite any template in the UI.

Placeholders the harness substitutes at send time are listed in
``TEMPLATE_PLACEHOLDERS``; any it does not recognise is left untouched so the
operator can keep their own bracketed notes.
"""

from __future__ import annotations

from typing import Dict, List, NamedTuple


class PromptStage(NamedTuple):
    """One named stage of the operator's prompt workflow."""

    key: str
    label: str
    description: str
    template: str
''']

    stages = []
    for const, fragments, label, description in PROMPT_SOURCES:
        text, filename = load(fragments)
        parts.append("\n# Source: %s\n%s_TEMPLATE = %s\n" % (filename, const, literal(text)))
        stages.append((const, label, description))

    parts.append("\nSTAGES: List[PromptStage] = [")
    for const, label, description in stages:
        parts.append('    PromptStage("%s", "%s", "%s", %s_TEMPLATE),'
                     % (const.lower(), label, description, const))
    parts.append("]\n")
    parts.append("STAGE_BY_KEY: Dict[str, PromptStage] = {s.key: s for s in STAGES}\n")
    parts.append('STAGE_KEYS: List[str] = [s.key for s in STAGES]\n')
    write(os.path.join(PKG, "prompt_templates.py"), "\n".join(parts))


if __name__ == "__main__":
    build_defaults()
    build_prompts()
